fn core_outputs_are_frozen() {
    for (seed, expected) in SEEDS.iter().zip(&GOLDENS) {
        assert_eq!(&compute(*seed), expected, "seed {seed}");
    }
}

// --- sampling goldens ---------------------------------------------------------------------------

#[derive(Debug, PartialEq)]
struct SamplingGolden {
    range_u8_0_10: [u8; 16],
    range_i16_incl: [i16; 16],
    range_usize_0_1000: [usize; 16],
    range_isize_bounded: [i64; 16],
    range_i64_full: [i64; 16],
    range_f32_bits: [u32; 16],
    range_f64_incl_bits: [u64; 16],
    shuffle_0_10: [u8; 10],
    choose_7: [u8; 16],
    fill_13: [u8; 13],
}

/// Each category is drawn from a fresh `Prng::from_seed(seed)`.
fn compute_sampling(seed: u64) -> SamplingGolden {
    let fresh = || Prng::from_seed(seed);
    let items = [10_u8, 20, 30, 40, 50, 60, 70];
    SamplingGolden {
        range_u8_0_10: {
            let mut p = fresh();
            core::array::from_fn(|_| p.range(0_u8..10))
        },
        range_i16_incl: {
            let mut p = fresh();
            core::array::from_fn(|_| p.range(-5_i16..=5))
        },
        range_usize_0_1000: {
            let mut p = fresh();
            core::array::from_fn(|_| p.range(0_usize..1000))
        },
        range_isize_bounded: {
            // Bounds that fit a 32-bit isize, so the same call runs on every target.
            let mut p = fresh();
            core::array::from_fn(|_| p.range(-2_000_000_000_isize..=2_000_000_000) as i64)
        },
        range_i64_full: {
            let mut p = fresh();
            core::array::from_fn(|_| p.range(i64::MIN..=i64::MAX))
        },
        range_f32_bits: {
            let mut p = fresh();
            core::array::from_fn(|_| p.range(0.0_f32..1.0).to_bits())
        },
        range_f64_incl_bits: {
            let mut p = fresh();
            core::array::from_fn(|_| p.range(-1.0_f64..=1.0).to_bits())
        },
        shuffle_0_10: {
            let mut p = fresh();
            let mut v: [u8; 10] = core::array::from_fn(|i| u8::try_from(i).expect("i < 10"));
            p.shuffle(&mut v);
            v
        },
        choose_7: {
            let mut p = fresh();
            core::array::from_fn(|_| *p.choose(&items).expect("non-empty"))
        },
        fill_13: {
            let mut p = fresh();
            let mut buf = [0_u8; 13];
            p.fill_bytes(&mut buf);
            buf
        },
    }
}

