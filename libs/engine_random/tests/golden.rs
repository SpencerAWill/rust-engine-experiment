//! Frozen golden values. Output streams are stable for all of 0.x: a change here is a
//! breaking change that requires an ADR. Never regenerate these to make a test pass.

use engine_random::Prng;

const SEEDS: [u64; 4] = [0, 1, 42, u64::MAX];

#[derive(Debug, PartialEq)]
struct Golden {
    u64s: [u64; 16],
    u32s: [u32; 16],
    f32_bits: [u32; 16],
    f64_bits: [u64; 16],
    bools: [bool; 16],
    stream_7: u64,
}

/// Each category is drawn from a fresh `Prng::from_seed(seed)`.
fn compute(seed: u64) -> Golden {
    let fresh = || Prng::from_seed(seed);
    Golden {
        u64s: {
            let mut p = fresh();
            core::array::from_fn(|_| p.next_u64())
        },
        u32s: {
            let mut p = fresh();
            core::array::from_fn(|_| p.next_u32())
        },
        f32_bits: {
            let mut p = fresh();
            core::array::from_fn(|_| p.next_f32().to_bits())
        },
        f64_bits: {
            let mut p = fresh();
            core::array::from_fn(|_| p.next_f64().to_bits())
        },
        bools: {
            let mut p = fresh();
            core::array::from_fn(|_| p.next_bool())
        },
        stream_7: fresh().stream(7).next_u64(),
    }
}

